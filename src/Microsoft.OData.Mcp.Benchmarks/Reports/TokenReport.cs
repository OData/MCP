using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using System.Text.Json;
using System.Threading.Tasks;
using Microsoft.OData.Mcp.Benchmarks.Infrastructure;

namespace Microsoft.OData.Mcp.Benchmarks.Reports
{

    /// <summary>
    /// Tokenizes every file in the linked <c>Before/</c> and <c>Current/</c> baselines and writes <c>TOKENS.md</c>:
    /// one paired table, then a per-section breakdown of the <c>tools.list</c> aggregate.
    /// </summary>
    /// <remarks>
    /// The baselines live in <c>src/Microsoft.OData.Mcp.Tests.Core/Baselines/TypeShapes</c> and are linked into this
    /// project's output, so the report always reads the files the tests assert.
    /// </remarks>
    public static class TokenReport
    {

        #region Fields

        /// <summary>
        /// The report file name.
        /// </summary>
        public const string FileName = "TOKENS.md";

        /// <summary>
        /// The aggregate baseline that gets the per-section breakdown.
        /// </summary>
        public const string ToolsListBaseline = "northwind.tools.list.json";

        /// <summary>
        /// Repository-relative location of the baselines, for the report header.
        /// </summary>
        public const string BaselinesLink = "../../Microsoft.OData.Mcp.Tests.Core/Baselines/TypeShapes";

        #endregion

        #region Public Methods

        /// <summary>
        /// Builds the markdown report from the linked baselines.
        /// </summary>
        /// <returns>
        /// Markdown with LF line endings.
        /// </returns>
        public static string Build()
        {
            var root = RepositoryPaths.BaselinesDirectory();
            var counts = CountPairs(root);
            var report = new StringBuilder();
            report.Append("# Token baselines\n\n");
            report.Append($"`{Tokenizer.EncodingName}` token counts of every file in [`Before/`]({BaselinesLink}/Before) and [`Current/`]({BaselinesLink}/Current). ");
            report.Append("Generated by `dotnet run -c Release -- --tokens` in `Microsoft.OData.Mcp.Benchmarks`; do not edit by hand. ");
            report.Append($"Where each `Before/` file came from is recorded in [`README.md`]({BaselinesLink}/README.md).\n\n");
            report.Append("| Baseline | Before | Current | Delta | Change |\n");
            report.Append("|---|---:|---:|---:|---:|\n");

            var pairedBefore = 0;
            var pairedCurrent = 0;
            var newOnly = 0;
            foreach (var pair in counts)
            {
                var (before, current) = pair.Value;
                if (before is int b && current is int c)
                {
                    pairedBefore += b;
                    pairedCurrent += c;
                    report.Append($"| `{pair.Key}` | {b} | {c} | {FormatDelta(c - b)} | {FormatPercent(b, c)} |\n");
                }
                else if (current is int only)
                {
                    newOnly += only;
                    report.Append($"| `{pair.Key}` | — | {only} | — | new |\n");
                }
                else if (before is int gone)
                {
                    report.Append($"| `{pair.Key}` | {gone} | — | — | removed |\n");
                }
            }

            report.Append($"| **Paired total** | **{pairedBefore}** | **{pairedCurrent}** | **{FormatDelta(pairedCurrent - pairedBefore)}** | **{FormatPercent(pairedBefore, pairedCurrent)}** |\n");
            report.Append($"| **New payloads (no Before)** | — | **{newOnly}** | — | — |\n");

            var beforeList = Path.Combine(root, "Before", ToolsListBaseline);
            var currentList = Path.Combine(root, "Current", ToolsListBaseline);
            if (File.Exists(beforeList) && File.Exists(currentList))
            {
                report.Append($"\n## `{ToolsListBaseline}` by section\n\n");
                report.Append("Descriptions and instructions are counted as plain text; schemas as JSON.\n\n");
                report.Append("| Section | Before | Current | Delta |\n");
                report.Append("|---|---:|---:|---:|\n");
                var beforeSections = CountSections(File.ReadAllText(beforeList));
                var currentSections = CountSections(File.ReadAllText(currentList));
                foreach (var key in beforeSections.Keys.Concat(currentSections.Keys).Distinct(StringComparer.Ordinal).OrderBy(key => key, StringComparer.Ordinal))
                {
                    var hasBefore = beforeSections.TryGetValue(key, out var b);
                    var hasCurrent = currentSections.TryGetValue(key, out var c);
                    var delta = hasBefore && hasCurrent ? FormatDelta(c - b) : "—";
                    report.Append($"| `{key}` | {(hasBefore ? b.ToString() : "—")} | {(hasCurrent ? c.ToString() : "—")} | {delta} |\n");
                }
            }

            return report.ToString();
        }

        /// <summary>
        /// Counts tokens for every file name that exists in <c>Before/</c>, <c>Current/</c>, or both.
        /// </summary>
        /// <param name="root">The baselines folder holding <c>Before/</c> and <c>Current/</c>.</param>
        /// <returns>
        /// File name to <c>(Before, Current)</c> counts in ordinal order; a side that lacks the file is <c>null</c>.
        /// </returns>
        public static SortedDictionary<string, (int? Before, int? Current)> CountPairs(string root)
        {
            ArgumentException.ThrowIfNullOrWhiteSpace(root);

            var before = Path.Combine(root, "Before");
            var current = Path.Combine(root, "Current");
            var names = Directory.EnumerateFiles(before).Concat(Directory.EnumerateFiles(current))
                .Select(Path.GetFileName)
                .OfType<string>()
                .Where(name => !name.EndsWith(".md", StringComparison.OrdinalIgnoreCase))
                .Distinct(StringComparer.Ordinal);

            var result = new SortedDictionary<string, (int? Before, int? Current)>(StringComparer.Ordinal);
            foreach (var name in names)
            {
                var beforePath = Path.Combine(before, name);
                var currentPath = Path.Combine(current, name);
                result[name] = (
                    File.Exists(beforePath) ? Tokenizer.Count(File.ReadAllText(beforePath)) : null,
                    File.Exists(currentPath) ? Tokenizer.Count(File.ReadAllText(currentPath)) : null);
            }

            return result;
        }

        /// <summary>
        /// Counts tokens per top-level section of a <c>tools.list</c> aggregate, plus per tool inside
        /// <c>generics</c> and <c>descriptions</c>.
        /// </summary>
        /// <param name="json">The aggregate JSON.</param>
        /// <returns>
        /// Section path to token count. Strings are counted as plain text, everything else as raw JSON.
        /// </returns>
        public static Dictionary<string, int> CountSections(string json)
        {
            ArgumentException.ThrowIfNullOrWhiteSpace(json);

            using var document = JsonDocument.Parse(json);
            var result = new Dictionary<string, int>(StringComparer.Ordinal);
            foreach (var property in document.RootElement.EnumerateObject())
            {
                result[property.Name] = CountElement(property.Value);
                if (property.Value.ValueKind == JsonValueKind.Object && property.Name is "generics" or "descriptions")
                {
                    foreach (var inner in property.Value.EnumerateObject())
                    {
                        result[$"{property.Name}.{inner.Name}"] = CountElement(inner.Value);
                    }
                }
            }

            return result;
        }

        /// <summary>
        /// Formats a token delta with an explicit sign.
        /// </summary>
        /// <param name="delta">Current minus Before.</param>
        /// <returns>
        /// <c>+12</c>, <c>-12</c>, or <c>0</c>.
        /// </returns>
        public static string FormatDelta(int delta)
        {
            return delta.ToString("+#;-#;0");
        }

        /// <summary>
        /// Formats the percentage change from <paramref name="before"/> to <paramref name="current"/>.
        /// </summary>
        /// <param name="before">The Before count.</param>
        /// <param name="current">The Current count.</param>
        /// <returns>
        /// One decimal with an explicit sign and a percent sign, or an em dash when <paramref name="before"/> is zero.
        /// </returns>
        public static string FormatPercent(int before, int current)
        {
            if (before == 0)
            {
                return "—";
            }

            return ((double)(current - before) / before * 100).ToString("+0.0;-0.0;0.0") + "%";
        }

        /// <summary>
        /// Writes <see cref="FileName"/> into <paramref name="outputDirectory"/>.
        /// </summary>
        /// <param name="outputDirectory">An existing directory.</param>
        /// <returns>
        /// A task that completes when the file is written.
        /// </returns>
        public static async Task WriteAsync(string outputDirectory)
        {
            ArgumentException.ThrowIfNullOrWhiteSpace(outputDirectory);

            var path = Path.Combine(outputDirectory, FileName);
            await File.WriteAllTextAsync(path, Build(), new UTF8Encoding(false)).ConfigureAwait(false);
            Console.WriteLine($"  {FileName}");
        }

        #endregion

        #region Internal Methods

        /// <summary>
        /// Counts one JSON element: strings as plain text, everything else as raw JSON.
        /// </summary>
        /// <param name="element">The element.</param>
        /// <returns>
        /// The token count.
        /// </returns>
        internal static int CountElement(JsonElement element)
        {
            return element.ValueKind == JsonValueKind.String ? Tokenizer.Count(element.GetString() ?? string.Empty) : Tokenizer.Count(element.GetRawText());
        }

        #endregion

    }

}
